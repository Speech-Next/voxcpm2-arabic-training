#!/bin/bash
# #12 follow-up, unattended: per-adapter LocDiT LoRAs for the Arabic distilled LocDiT (its weights frozen; every
#   adapter's LocDiT LoRA tuned for it, initialized from the adapter's own, distill/student_lora.py) on #12's recorded
#   teacher data: mse -> spectral -> dmd. Then TRAIN_DONE, and the evaluation on #2 (v2 set, ref cloning, int8, head
#   start 8), the engine (ENGINE: one with dialect_tts.student_adapters) loading each stage's LoRAs next to the student
#   (ship-<stage>/student_k2_dmd.pt + student_k2_dmd.adapters/), against the student with the adapters' own LoRAs and
#   the adapters with the original LocDiT (base-adapters-int8).
#     scripts/run_student_lora.sh [name]          log: /workspace/data/arabic/logs/<name>.log
# Every GPU step holds GPU_LOCK (flock; default /workspace/.gpu.lock, empty: no lock) while it runs; other GPU jobs that
# take the same lock run between two steps.
# The baseline: the student's existing run on #2 (BASE_RUN, dit-adapters-dmd) when this engine still generates it
# bit for bit (the whole set regenerated and compared), else a new run of it. The student's own file (STUDENT, the Hub
# snapshot) has no .adapters/ next to it, so the baseline runs every adapter with its own LoRA.
# Environment (defaults): ENGINE, ENGINE_PY, TRAIN_PY, SCORE_PY, MODEL, TD (teacher data), SD (runs dir), STUDENT,
# MSE_ITERS, SPEC_ITERS, DMD_ITERS, EVAL_STAGES (stage directories under SD), STOP_AFTER (mse, spectral, dmd or
# train), and extra options per stage: MSE_ARGS, SPEC_ARGS, DMD_ARGS.
# Every finished step is skipped (a stage that stopped midway starts again).
set -euo pipefail
NAME=${1:-student-lora}
REPO=$(cd "$(dirname "$0")/.." && pwd)
ENGINE=${ENGINE:-/workspace/voxcpm2-arabic-dialects-turbo}
ENGINE_PY=${ENGINE_PY:-/workspace/voxcpm2-arabic-dialects-turbo/.venv/bin/python}
TRAIN_PY=${TRAIN_PY:-/workspace/envs/train/bin/python}
[ -x "$TRAIN_PY" ] || TRAIN_PY=$ENGINE_PY
SCORE_PY=${SCORE_PY:-/workspace/envs/eval/bin/python}
[ -x "$SCORE_PY" ] || SCORE_PY=/venv/main/bin/python
MODEL=${MODEL:-$("$TRAIN_PY" -c "from huggingface_hub import snapshot_download as s; print(s('VoxCPM-Kernel/VoxCPM2-Arabic-Dialects', local_files_only=True))")}
STUDENT=${STUDENT:-VoxCPM-Kernel/VoxCPM2-Arabic-Dialects-Distilled-DiT:student_k2_dmd.pt}
GPU_LOCK=${GPU_LOCK-/workspace/.gpu.lock}
SET=${SET:-v2}
TD=${TD:-/workspace/data/arabic/teacher/adapters}
SD=${SD:-/workspace/runs/$NAME}
MSE_ITERS=${MSE_ITERS:-2500}; SPEC_ITERS=${SPEC_ITERS:-1000}; DMD_ITERS=${DMD_ITERS:-1000}
EVAL_STAGES=${EVAL_STAGES:-dmd-last spectral-best}
STOP_AFTER=${STOP_AFTER:-}
BASE_RUN=${BASE_RUN:-dit-adapters-dmd}
EVAL=/workspace/data/arabic/eval/runs
LOG=${LOG:-/workspace/data/arabic/logs/$NAME.log}
mkdir -p "$SD" "$(dirname "$LOG")"
exec >> "$LOG" 2>&1
if [ -f /workspace/.env ]; then set -a; . /workspace/.env; set +a; fi
export PYTORCH_ALLOC_CONF=expandable_segments:True
step() { echo "=== $(date +%F\ %T) $*"; }
stop_after() { [ "$STOP_AFTER" = "$1" ] && { step "stop after $1 (STOP_AFTER)"; exit 0; }; return 0; }
gpu() {  # a GPU step, holding GPU_LOCK while it runs
  if [ -z "$GPU_LOCK" ]; then "$@"; return; fi
  ( flock 9; "$@" ) 9>>"$GPU_LOCK"
}
train() { (cd "$REPO" && PYTHONPATH="$REPO" "$TRAIN_PY" "$@"); }
stage() {  # stage, iterations, init, [student_lora.py args]
  local stage=$1 iters=$2 init=$3; shift 3
  [ -f "$SD/$stage-done" ] && return 0
  gpu train -m arabic_voxcpm.distill.student_lora --teacher "$MODEL" --data "$TD" --student "$STUDENT" --out "$SD" \
    --stage "$stage" --iters "$iters" --init "$init" "$@" && touch "$SD/$stage-done"
}
evalrun() {  # run name, checkpoint, [run.py args]: generate (once) -> score -> report
  local name=$1 dit=$2; shift 2
  (cd "$REPO" && PYTHONPATH="$REPO" "$SCORE_PY" -m arabic_voxcpm.eval.run --engine-python "$ENGINE_PY" \
     --engine-path "$ENGINE" --name "$name" --model "$MODEL" --set "$SET" --mode ref --dit "$dit" --precision int8 \
     --head-tokens 8 --gpu-memory-utilization "${EVAL_GPU_UTIL:-0.45}" --kv-blocks "${EVAL_KV_BLOCKS:-256}" "$@")
}
ship() {  # stage directory -> ship-<it>/: the student next to its LoRAs, as the engine finds them
  local d=$SD/ship-$1
  mkdir -p "$d"
  ln -sfn "$STUDENT_PT" "$d/student_k2_dmd.pt"
  ln -sfn "$SD/$1" "$d/student_k2_dmd.adapters"
  echo "$d/student_k2_dmd.pt"
}
same_audio() {  # the base run regenerated by this engine into $SD/base-check: every file equal to $EVAL/$BASE_RUN's
  local out=$SD/base-check cfg=$EVAL/$BASE_RUN/run.json
  rm -rf "$out"
  (cd "$REPO" && PYTHONPATH="$REPO:$ENGINE" "$ENGINE_PY" -m arabic_voxcpm.eval.generate --set "$SET" --out "$out" \
     --model "$MODEL" --dit "$STUDENT_PT" --precision int8 --head-tokens 8 --mode ref --seeds 2000 2001 \
     --concurrency "$("$SCORE_PY" -c "import json; print(json.load(open('$cfg'))['concurrency'])")" \
     --gpu-memory-utilization "${EVAL_GPU_UTIL:-0.45}" --kv-blocks "${EVAL_KV_BLOCKS:-256}")
  "$SCORE_PY" - "$out/wav" "$EVAL/$BASE_RUN/wav" <<'EOF'
import filecmp, os, sys
a, b = sys.argv[1:]
names = sorted(os.listdir(b))
diff = [n for n in names if not os.path.exists(os.path.join(a, n)) or not filecmp.cmp(os.path.join(a, n), os.path.join(b, n), shallow=False)]
print(f"base check: {len(names) - len(diff)} / {len(names)} files equal")
sys.exit(1 if diff or len(os.listdir(a)) != len(names) else 0)
EOF
}

step "$NAME: model $MODEL, student $STUDENT, data $TD, runs $SD, train python $TRAIN_PY, engine $ENGINE"
STUDENT_PT=$("$TRAIN_PY" -c "
import sys; sys.path.insert(0, '$REPO')
from arabic_voxcpm.distill.dit import resolve; print(resolve('$STUDENT'))")
step "mse ($MSE_ITERS iterations, from the adapters' own LoRAs)"
stage mse "$MSE_ITERS" adapters --lr 5e-5 --rows 64 --micro 128 ${MSE_ARGS:-}
stop_after mse
step "spectral ($SPEC_ITERS iterations, from mse-best)"
stage spectral "$SPEC_ITERS" "$SD/mse-best" --lr 2.5e-5 --rows 32 --micro 32 ${SPEC_ARGS:-}
stop_after spectral
step "dmd ($DMD_ITERS iterations, from spectral-best)"
stage dmd "$DMD_ITERS" "$SD/spectral-best" --lr 2.5e-5 --rows 64 --micro 64 ${DMD_ARGS:-}
stop_after dmd
echo "training done $(date +%F\ %T): mse, spectral, dmd in $SD" > "$SD/TRAIN_DONE"
stop_after train

step "evaluation on $SET (ref, int8, head start 8), engine $ENGINE"
BASE=$NAME-base
if gpu same_audio; then BASE=$BASE_RUN; else gpu evalrun "$BASE" "$STUDENT_PT" --no-report; fi
step "baseline: $BASE"
for s in $EVAL_STAGES; do
  gpu evalrun "$NAME-$s" "$(ship "$s")" --baseline "$BASE" base-adapters-int8
done
step "report"
(cd "$REPO" && PYTHONPATH="$REPO" "$SCORE_PY" -m arabic_voxcpm.eval.report --base "$EVAL/$BASE" \
   "$EVAL/base-adapters-int8-$SET-ref" $(for s in $EVAL_STAGES; do echo "$EVAL/$NAME-$s"; done) \
   --md "$SD/report.md" --json "$SD/report.json")
step "done"
