"""Blind A/B listening test of two runs for native speakers, and its un-blinding (issue #2).

    python -m arabic_voxcpm.eval.listen --a <run A> --b <run B> --out <dir> [--groups eg najdi ...] [--n-per-group 10]
    python -m arabic_voxcpm.eval.listen --score <answers.csv> [...] --key <dir>/key.json

Export: per group, n items generated by both runs (one common seed each), drawn at random; each item's two clips in
random order as "A" and "B". Written: <dir>/page/ (index.html: self-contained, no external resources; the Arabic text
right to left, two players per item, "more natural" and "more like the dialect" each A / B / same, answers kept in the
browser and downloaded as CSV; audio/: the clips, copied or --link'ed) to share, and <dir>/items.csv, <dir>/key.json
(which run is behind each letter) that stay with the organizer.

Score: the answers of any number of listeners un-blinded by the key; per question and group, run B's win rate over the
decisive answers with a Wilson 95 % interval, the ties, and B's score with a tie as half a win.
"""

from __future__ import annotations

import argparse
import csv
import html
import json
import math
import os
import random
import shutil
from collections import defaultdict

from arabic_voxcpm.eval import common

QUESTIONS = (("natural", "أيهما أكثر طبيعية؟", "more natural"),
             ("dialect", "أيهما أقرب إلى اللهجة؟", "more like the dialect"))
CHOICES = (("A", "A"), ("B", "B"), ("same", "متساويان"))
GROUP_AR = {"msa": "الفصحى", "eg": "المصرية", "ps": "الفلسطينية", "lb": "اللبنانية", "sy": "السورية", "iq": "العراقية",
            "sa": "السعودية", "najdi": "النجدية", "hejazi": "الحجازية", "khaliji": "الخليجية", "bh": "البحرينية",
            "ye": "اليمنية", "sd": "السودانية", "ly": "الليبية", "tn": "التونسية", "dz": "الجزائرية", "ma": "المغربية"}


def wavs(run: str) -> dict:
    """(item id, seed) -> wav path of a run's finished clips."""
    d = os.path.join(run, "wav")
    return {k: os.path.join(d, n) for n in sorted(os.listdir(d)) if (k := common.parse_wav(n))}


def choose(items: list[dict], a: dict, b: dict, groups: list[str] | None, n: int, rng: random.Random) -> list[dict]:
    """Trials: per group n items present in both runs (a common seed drawn per item), each with the run behind "A"."""
    seeds = defaultdict(list)
    for iid, s in sorted(set(a) & set(b)):
        seeds[iid].append(s)
    by_group = defaultdict(list)
    for it in items:
        if it["id"] in seeds:
            by_group[it["group"]].append(it)
    trials = []
    for g in groups or sorted(by_group):
        pool = by_group.get(g, [])
        for it in rng.sample(pool, min(n, len(pool))):
            trials.append({"trial": len(trials) + 1, "group": g, "id": it["id"], "seed": rng.choice(seeds[it["id"]]),
                           "text": it["text"], "A": rng.choice("ab")})
    return trials


def page(trials: list[dict], title: str) -> str:
    """The listening page: one self-contained HTML file next to audio/."""
    cards, last = [], None
    for t in trials:
        if t["group"] != last:
            last = t["group"]
            cards.append(f'<h2 id="g-{last}">{html.escape(GROUP_AR.get(last, last))} <small>({html.escape(last)})</small></h2>')
        qs = []
        for q, ar, en in QUESTIONS:
            opts = "".join(f'<label><input type="radio" name="{q}-{t["trial"]}" value="{v}"> {html.escape(lab)}</label>'
                           for v, lab in CHOICES)
            qs.append(f'<fieldset><legend>{ar} <small>{en}</small></legend>{opts}</fieldset>')
        cards.append(
            f'<section class="card" data-trial="{t["trial"]}" data-group="{html.escape(t["group"])}">'
            f'<div class="num">{t["trial"]}</div><p class="text" lang="ar" dir="rtl">{html.escape(t["text"])}</p>'
            f'<div class="players"><div><b>A</b><audio controls preload="none" src="audio/{t["trial"]:04d}A.wav"></audio></div>'
            f'<div><b>B</b><audio controls preload="none" src="audio/{t["trial"]:04d}B.wav"></audio></div></div>'
            + "".join(qs) + "</section>")
    nav = " · ".join(f'<a href="#g-{g}">{html.escape(GROUP_AR.get(g, g))}</a>' for g in dict.fromkeys(t["group"] for t in trials))
    return _PAGE.replace("{{title}}", html.escape(title)).replace("{{n}}", str(len(trials))).replace(
        "{{nav}}", nav).replace("{{cards}}", "\n".join(cards))


def export(a: str, b: str, out: str, groups=None, n: int = 10, seed: int = 0, link: bool = False) -> list[dict]:
    ca, cb = common.run_config(a), common.run_config(b)
    if os.path.realpath(ca["set"]) != os.path.realpath(cb["set"]):
        raise SystemExit(f"the runs are of different sets: {ca['set']} and {cb['set']}")
    rng = random.Random(seed)
    wa, wb = wavs(a), wavs(b)
    trials = choose(common.items(ca["set"]), wa, wb, groups, n, rng)
    if not trials:
        raise SystemExit("no item generated by both runs")
    audio = os.path.join(out, "page", "audio")
    os.makedirs(audio, exist_ok=True)
    for t in trials:
        src = {"a": wa[t["id"], t["seed"]], "b": wb[t["id"], t["seed"]]}
        for letter, run in (("A", t["A"]), ("B", "b" if t["A"] == "a" else "a")):
            dst = os.path.join(audio, f"{t['trial']:04d}{letter}.wav")
            if os.path.exists(dst):
                os.remove(dst)
            if link:
                try:
                    os.link(src[run], dst)
                    continue
                except OSError:
                    pass
            shutil.copyfile(src[run], dst)
    open(os.path.join(out, "page", "index.html"), "w", encoding="utf-8").write(page(trials, "اختبار استماع"))
    with open(os.path.join(out, "items.csv"), "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["trial", "group", "id", "seed", "text", "audio_A", "audio_B"])
        for t in trials:
            w.writerow([t["trial"], t["group"], t["id"], t["seed"], t["text"], f"audio/{t['trial']:04d}A.wav",
                        f"audio/{t['trial']:04d}B.wav"])
    key = {"a": os.path.abspath(a), "b": os.path.abspath(b), "set": ca["set"], "seed": seed,
           "trials": [{k: t[k] for k in ("trial", "group", "id", "seed", "A")} for t in trials]}
    json.dump(key, open(os.path.join(out, "key.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    return trials


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    c = (p + z * z / (2 * n)) / (1 + z * z / n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return c - h, c + h


def score(answers: list[str], key_path: str) -> dict:
    """{question: {group | "ALL": {"a", "b", "same", "n", "win_b", "ci", "score_b"}}} from answer CSVs."""
    key = json.load(open(key_path, encoding="utf-8"))
    trials = {t["trial"]: t for t in key["trials"]}
    counts = {q: defaultdict(lambda: {"a": 0, "b": 0, "same": 0}) for q, _, _ in QUESTIONS}
    for path in answers:
        for row in csv.DictReader(open(path, encoding="utf-8-sig")):  # the page writes a BOM (spreadsheets)
            t = trials.get(int(row["trial"]))
            if t is None:
                raise SystemExit(f"{path}: trial {row['trial']} is not in the key (another export?)")
            for q, _, _ in QUESTIONS:
                v = (row.get(q) or "").strip()
                if not v:
                    continue
                if v not in ("A", "B", "same"):
                    raise SystemExit(f"{path}: trial {row['trial']}: {q} = {v!r}, not A, B or same")
                who = "same" if v == "same" else t["A"] if v == "A" else ("b" if t["A"] == "a" else "a")
                for g in (t["group"], "ALL"):
                    counts[q][g][who] += 1
    out = {}
    for q, by in counts.items():
        out[q] = {}
        for g, c in by.items():
            dec = c["a"] + c["b"]
            n = dec + c["same"]
            out[q][g] = {**c, "n": n, "win_b": c["b"] / dec if dec else float("nan"), "ci": list(wilson(c["b"], dec)),
                         "score_b": (c["b"] + 0.5 * c["same"]) / n if n else float("nan")}
    return out


def fmt(res: dict, key_path: str) -> str:
    key = json.load(open(key_path, encoding="utf-8"))
    name = lambda r: os.path.basename(r.rstrip("/"))  # noqa: E731
    lines = [f"A/B listening: run a = `{name(key['a'])}`, run b = `{name(key['b'])}`. B win rate over decisive answers "
             "(Wilson 95 % interval; above 50 % with the interval excluding it: b preferred), ties, b's score with a tie "
             "as half a win."]
    for q, ar, en in QUESTIONS:
        lines += ["", f"### {en}", "", "| group | answers | a | b | same | b win rate | 95 % interval | b score |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|"]
        for g in sorted(res[q], key=lambda g: (g == "ALL", g)):
            r = res[q][g]
            lines.append(f"| {g} | {r['n']} | {r['a']} | {r['b']} | {r['same']} | {100 * r['win_b']:.0f} % | "
                         f"[{100 * r['ci'][0]:.0f}, {100 * r['ci'][1]:.0f}] | {100 * r['score_b']:.0f} % |")
    return "\n".join(lines)


