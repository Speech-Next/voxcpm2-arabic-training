"""Labelled A/B listening pairs that always hold words, shared as a Hugging Face dataset (e.g. #10's seam check).

    python -m arabic_voxcpm.eval.pairs --a <run A> --b <run B> --labels main "PR #23" --out <dir> \
        [--groups eg najdi ...] [--n-per-group 1] [--min-s 1.0] [--min-words 2] [--push <dataset id>]

Per group, n items generated by both runs (seed 2000 first). Each clip of a pair is the opening of its sentence, cut
after whole words: at least --min-words words and --min-s seconds, ending in the pause after a word (a short fade, no
click). Whisper large-v3 word timestamps place the cut, and a second pass on the cut clip checks the words are heard.

An item that fails the word check in one of the runs is skipped and reported: Whisper hears no word in the first
--max-onset seconds, the opening does not match the text's first word (hallucinated filler, "اشتركوا في القناة", is
what Whisper writes on noise), or the cut clip loses its words. Written: <dir>/audio/ (the wavs), <dir>/data/ (one
parquet file, a row per pair: dialect, words and both versions as audio columns, so the dataset viewer plays them
side by side), <dir>/README.md (the card), <dir>/pairs.json and <dir>/skipped.json. --push uploads the folder
(replacing data/ and audio/) as a gated dataset: the voices are cloned from the gated reference set.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import random
import re
from collections import defaultdict

import numpy as np

from arabic_voxcpm.eval import common
from arabic_voxcpm.eval.listen import GROUP_AR, wavs
from arabic_voxcpm.eval.metrics import WHISPER, normalize_ar

FADE_S = 0.02  # fade-out at the cut
GAP_S = 0.15  # silence kept after the last word (less when the next word starts sooner)


def words_of(model, path: str) -> list[tuple[str, float, float]]:
    """(word, start s, end s) by Whisper large-v3 (faster-whisper model)."""
    segs, _ = model.transcribe(path, language="ar", beam_size=5, word_timestamps=True, vad_filter=False,
                               condition_on_previous_text=False)
    return [(w.word.strip(), w.start, w.end) for s in segs for w in s.words if w.word.strip()]


def opening_ok(words: list[tuple[str, float, float]], text: str, max_onset: float = 1.0) -> bool:
    """The clip opens with speech: its first heard word starts within max_onset s and matches the text's first word
    (the first two heard words cover it: Whisper may split or join a clitic)."""
    ref = normalize_ar(text).split()
    if not words or not ref or words[0][1] > max_onset:
        return False
    head = normalize_ar(" ".join(w for w, _, _ in words[:2])).replace(" ", "")
    first = ref[0]
    return difflib.SequenceMatcher(None, first, head[:len(first) + 2]).ratio() >= 0.6


def cut_point(words: list[tuple[str, float, float]], min_s: float, min_words: int,
              duration: float) -> tuple[float, int] | None:
    """(cut s, words kept): after the first word k >= min_words that ends at or after min_s, in the pause before the
    next word (GAP_S at most). None: the clip has fewer words than that."""
    for k, (_, _, end) in enumerate(words, 1):
        if k >= min_words and end >= min_s:
            nxt = words[k][1] if k < len(words) else duration
            return min(end + GAP_S, max(end, nxt), duration), k
    return None


def cut(audio: np.ndarray, sr: int, at: float) -> np.ndarray:
    n = min(len(audio), int(round(at * sr)))
    out = audio[:n].copy()
    f = min(n, int(FADE_S * sr))
    if f:
        out[n - f:] *= np.linspace(1.0, 0.0, f, dtype=out.dtype)
    return out


def build(a: str, b: str, labels: tuple[str, str], out: str, groups=None, n: int = 1, min_s: float = 1.0,
          min_words: int = 2, max_onset: float = 1.0, seed: int = 0, model=None,
          device: str = "cuda") -> tuple[list[dict], list[dict]]:
    """(pairs, skipped): the pairs written to out/audio, and the items skipped by the word check."""
    import soundfile as sf

    ca, cb = common.run_config(a), common.run_config(b)
    if os.path.realpath(ca["set"]) != os.path.realpath(cb["set"]):
        raise SystemExit(f"the runs are of different sets: {ca['set']} and {cb['set']}")
    if model is None:
        from faster_whisper import WhisperModel

        model = WhisperModel(WHISPER, device=device, compute_type="float16" if device == "cuda" else "int8")
    wa, wb = wavs(a), wavs(b)
    both = set(wa) & set(wb)
    by_group = defaultdict(list)
    for it in common.items(ca["set"]):
        keys = sorted((k for k in both if k[0] == it["id"]), key=lambda k: (k[1] != 2000, k[1]))
        if keys:
            by_group[it["group"]].append((it, keys[0]))
    rng = random.Random(seed)
    data = os.path.join(out, "audio")
    os.makedirs(data, exist_ok=True)
    pairs, skipped = [], []
    for g in groups or sorted(by_group):
        pool = by_group.get(g, [])
        rng.shuffle(pool)
        got = 0
        for it, key in pool:
            if got >= n:
                break
            clips, why = {}, None
            for side, src in (("a", wa[key]), ("b", wb[key])):
                audio, sr = sf.read(src, dtype="float32")
                ws = words_of(model, src)
                if not opening_ok(ws, it["text"], max_onset):
                    why = f"{side}: no words at the start (heard: {' '.join(w for w, _, _ in ws[:3]) or 'nothing'})"
                    break
                cp = cut_point(ws, min_s, min_words, len(audio) / sr)
                if cp is None:
                    why = f"{side}: fewer than {min_words} words"
                    break
                clips[side] = (cut(audio, sr, cp[0]), sr, cp)
            stem = common.wav_name(*key)[:-4]
            if why is None:
                for side, (audio, sr, (at, k)) in clips.items():
                    path = os.path.join(data, f"{stem}__{side}.wav")
                    sf.write(path, audio, sr)
                    heard = words_of(model, path)
                    if len(heard) < min(min_words, k) or not opening_ok(heard, it["text"], max_onset):
                        why = f"{side}: the cut clip did not pass the word check"
                        break
                    clips[side] = clips[side] + (" ".join(w for w, _, _ in heard), at)
            if why is not None:
                skipped.append({"clip": stem, "group": g, "why": why})
                for side in ("a", "b"):
                    p = os.path.join(data, f"{stem}__{side}.wav")
                    if os.path.exists(p):
                        os.remove(p)
                continue
            k = min(clips["a"][2][1], clips["b"][2][1])
            pairs.append({"clip": stem, "group": g, "text": " ".join(it["text"].split()[:k]),
                          "a": {"asr": clips["a"][3], "s": round(clips["a"][4], 2)},
                          "b": {"asr": clips["b"][3], "s": round(clips["b"][4], 2)}})
            got += 1
    json.dump({"labels": list(labels), "pairs": pairs}, open(os.path.join(out, "pairs.json"), "w", encoding="utf-8"),
              indent=1, ensure_ascii=False)
    json.dump(skipped, open(os.path.join(out, "skipped.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    return pairs, skipped


def column(label: str) -> str:
    """A version's column name: "PR #23" -> pr_23."""
    return re.sub(r"\W+", "_", label.lower()).strip("_") or "version"


def write_table(out: str, pairs: list[dict], labels: tuple[str, str]) -> str:
    """out/data/test-00000-of-00001.parquet: a row per pair (dialect, words, both versions as Hugging Face Audio
    columns: struct of the wav bytes and its name, with the features in the schema metadata)."""
    import pyarrow as pa
    import pyarrow.parquet as pq

    ca, cb = (column(x) for x in labels)
    audio = pa.struct([("bytes", pa.binary()), ("path", pa.string())])
    cols = {"dialect": [], "words": [], ca: [], cb: []}
    for p in pairs:
        cols["dialect"].append(f"{GROUP_AR.get(p['group'], p['group'])} ({p['group']})")
        cols["words"].append(p["text"])
        for c, side in ((ca, "a"), (cb, "b")):
            name = f"{p['clip']}__{side}.wav"
            cols[c].append({"bytes": open(os.path.join(out, "audio", name), "rb").read(), "path": name})
    features = {"dialect": {"dtype": "string", "_type": "Value"}, "words": {"dtype": "string", "_type": "Value"},
                ca: {"_type": "Audio"}, cb: {"_type": "Audio"}}
    schema = pa.schema([("dialect", pa.string()), ("words", pa.string()), (ca, audio), (cb, audio)],
                       metadata={"huggingface": json.dumps({"info": {"features": features}})})
    os.makedirs(os.path.join(out, "data"), exist_ok=True)
    path = os.path.join(out, "data", "test-00000-of-00001.parquet")
    pq.write_table(pa.table(cols, schema=schema), path)
    return path


def card(pairs: list[dict], skipped: list[dict], labels: tuple[str, str], title: str, note: str,
         min_words: int = 2, min_s: float = 1.0, gated_from: str | None = None) -> str:
    la, lb = labels
    rows = "\n".join(
        f"| {GROUP_AR.get(p['group'], p['group'])} ({p['group']}) | {p['text']} | {p['a']['s']:.1f} s | "
        f"[{la}](audio/{p['clip']}__a.wav) | [{lb}](audio/{p['clip']}__b.wav) |" for p in pairs)
    lines = ["---", "configs:", "- config_name: default", "  data_files:", "  - split: test", "    path: data/*.parquet",
             "dataset_info:", "  features:", "  - name: dialect", "    dtype: string", "  - name: words",
             "    dtype: string", f"  - name: {column(la)}", "    dtype: audio", f"  - name: {column(lb)}",
             "    dtype: audio", "license: other", "task_categories:", "- text-to-speech", "language:", "- ar", "---",
             "", f"# {title}", "", note, "",
             f"The dataset viewer above plays both versions of a sentence side by side: one row per dialect, the "
             f"`{column(la)}` and `{column(lb)}` columns.", "",
             f"Each clip is the opening of a sentence, cut after whole words (at least {min_words} words and "
             f"{min_s:g} s), checked with Whisper large-v3 so that the words are heard.", "",
             f"| dialect | words | length | {la} | {lb} |", "|---|---|---:|---|---|", rows]
    if skipped:
        lines += ["", f"Skipped: {len(skipped)} sentence(s) that failed the word check (no word heard at the start, "
                  "an opening that does not match the text's first word, or a cut clip that lost its words): "
                  f"{', '.join(s['clip'] for s in skipped)}."]
    if gated_from:
        lines += ["", f"Gated: the voices are cloned from the gated [{gated_from.split('/')[-1]}]"
                  f"(https://huggingface.co/datasets/{gated_from})."]
    return "\n".join(lines) + "\n"


def push(out: str, repo: str, message: str) -> None:
    from huggingface_hub import HfApi

    api = HfApi()
    api.create_repo(repo, repo_type="dataset", exist_ok=True)
    api.upload_folder(repo_id=repo, repo_type="dataset", folder_path=out, delete_patterns=["data/*", "audio/*"],
                      commit_message=message)
    api.update_repo_settings(repo, repo_type="dataset", gated="manual")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--a", required=True, help="run A")
    ap.add_argument("--b", required=True, help="run B")
    ap.add_argument("--labels", nargs=2, default=["A", "B"], help="the two versions' names on the card")
    ap.add_argument("--out", required=True)
    ap.add_argument("--groups", nargs="+")
    ap.add_argument("--n-per-group", type=int, default=1)
    ap.add_argument("--min-s", type=float, default=1.0, help="shortest clip (seconds)")
    ap.add_argument("--min-words", type=int, default=2, help="fewest whole words per clip")
    ap.add_argument("--max-onset", type=float, default=1.0, help="the first word must start within this (seconds)")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--title", default="Listening check")
    ap.add_argument("--note", default="")
    ap.add_argument("--device", default="cuda", help="Whisper's device")
    ap.add_argument("--push", metavar="DATASET", help="upload to this Hugging Face dataset (gated)")
    args = ap.parse_args()
    labels = tuple(args.labels)
    pairs, skipped = build(common.run_dir(args.a), common.run_dir(args.b), labels, args.out, args.groups,
                           args.n_per_group, args.min_s, args.min_words, args.max_onset, args.seed,
                           device=args.device)
    write_table(args.out, pairs, labels)
    open(os.path.join(args.out, "README.md"), "w", encoding="utf-8").write(
        card(pairs, skipped, labels, args.title, args.note, args.min_words, args.min_s,
             "VoxCPM-Kernel/Arabic-Hindi-Reference-Voices"))
    print(f"{len(pairs)} pairs, {len(skipped)} skipped (word check) -> {args.out}")
    for s in skipped:
        print("  skipped", s["clip"], s["why"])
    if args.push:
        push(args.out, args.push, f"{args.title}: {len(pairs)} pairs")
        print("pushed", args.push)
